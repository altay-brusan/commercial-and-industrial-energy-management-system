// --- Curve mock data (24h, 5-min intervals) ---

function generateCurveData(consumer: Consumer): ConsumerCurveData {
  const consumption: ConsumerCurveData["consumption"] = [];
  const demand: ConsumerCurveData["demand"] = [];

  const now = new Date();
  const currentHour = now.getHours();
  const endMinute = currentHour <= 0 ? 0 : currentHour * 60 + now.getMinutes();

  const basePower = consumer.activePower ?? 100;
  const baseReactive = consumer.reactivePower ?? 15;
  const contracted = consumer.contractedCapacity;

  for (let m = 0; m <= Math.min(endMinute, 1440); m += 5) {
    const h = Math.floor(m / 60);
    const min = m % 60;
    const time = `${String(h).padStart(2, "0")}:${String(min).padStart(2, "0")}`;

    // Commercial/industrial load profile
    const morningRamp = Math.exp(-0.5 * Math.pow((h - 10) / 2.5, 2));
    const afternoonPeak = Math.exp(-0.5 * Math.pow((h - 14) / 2, 2));
    const eveningDip = h >= 18 ? 0.4 : 1.0;
    const loadProfile = 0.3 + 0.45 * morningRamp + 0.5 * afternoonPeak;
    const factor = loadProfile * eveningDip;

    const ap = +(basePower * factor * (1 + (Math.random() - 0.5) * 0.08)).toFixed(1);
    const rp = +(baseReactive * factor * (1 + (Math.random() - 0.5) * 0.1)).toFixed(1);

    consumption.push({ time, activePower: ap, reactivePower: rp });
    demand.push({ time, demand: ap, contracted });
  }

  return { consumption, demand };
}

const curveCache = new Map<string, ConsumerCurveData>();

export function getCurveDataForConsumer(consumerId: string): ConsumerCurveData {
  if (curveCache.has(consumerId)) return curveCache.get(consumerId)!;

  const consumer = consumers.find((c) => c.id === consumerId);
  if (!consumer || consumer.status === "offline") {
    return { consumption: [], demand: [] };
  }

  const data = generateCurveData(consumer);
  curveCache.set(consumerId, data);
  return data;
}
