// --- Curve mock data (24h, 5-min intervals, grid runs continuously) ---

function generateCurveData(device: GridDevice): GridCurveData {
  const power: GridCurveData["power"] = [];
  const voltage: GridCurveData["voltage"] = [];
  const frequency: GridCurveData["frequency"] = [];
  const powerFactor: GridCurveData["powerFactor"] = [];

  const now = new Date();
  const currentHour = now.getHours();
  const endMinute = currentHour <= 0 ? 0 : currentHour * 60 + now.getMinutes();

  const basePower = device.activePower ?? 500;
  const baseReactive = device.reactivePower ?? 80;
  const baseVoltage = device.voltagePhaseA ?? 5750;
  const basePF = device.powerFactor ?? 0.97;

  for (let m = 0; m <= Math.min(endMinute, 1440); m += 5) {
    const h = Math.floor(m / 60);
    const min = m % 60;
    const time = `${String(h).padStart(2, "0")}:${String(min).padStart(2, "0")}`;

    // Grid power varies with load profile (peaks at 10-12h and 18-20h)
    const morningPeak = Math.exp(-0.5 * Math.pow((h - 11) / 2, 2));
    const eveningPeak = Math.exp(-0.5 * Math.pow((h - 19) / 2, 2));
    const loadFactor = 0.5 + 0.35 * morningPeak + 0.5 * eveningPeak;

    const ap = +(basePower * loadFactor * (1 + (Math.random() - 0.5) * 0.08)).toFixed(1);
    const rp = +(baseReactive * loadFactor * (1 + (Math.random() - 0.5) * 0.1)).toFixed(1);
    const sp = +Math.sqrt(ap * ap + rp * rp).toFixed(1);

    power.push({ time, activePower: ap, reactivePower: rp, apparentPower: sp });

    // Voltage: base ±50V random walk
    const vA = +(baseVoltage + (Math.random() - 0.5) * 40).toFixed(0);
    const vB = +(baseVoltage - 15 + (Math.random() - 0.5) * 40).toFixed(0);
    const vC = +(baseVoltage + 10 + (Math.random() - 0.5) * 40).toFixed(0);
    voltage.push({ time, phaseA: vA, phaseB: vB, phaseC: vC });

    // Frequency: 50Hz ±0.1Hz
    const freq = +(50 + (Math.random() - 0.5) * 0.2).toFixed(3);
    frequency.push({ time, frequency: freq });

    // Power factor: slight variation
    const pf = +(basePF + (Math.random() - 0.5) * 0.04).toFixed(3);
    powerFactor.push({ time, powerFactor: Math.min(1, Math.max(0.85, pf)) });
  }

  return { power, voltage, frequency, powerFactor };
}

const curveCache = new Map<string, GridCurveData>();

export function getCurveDataForDevice(deviceId: string): GridCurveData {
  if (curveCache.has(deviceId)) return curveCache.get(deviceId)!;

  const device = gridDevices.find((d) => d.id === deviceId);
  if (!device || device.status === "offline") {
    return { power: [], voltage: [], frequency: [], powerFactor: [] };
  }

  const data = generateCurveData(device);
  curveCache.set(deviceId, data);
  return data;
}
