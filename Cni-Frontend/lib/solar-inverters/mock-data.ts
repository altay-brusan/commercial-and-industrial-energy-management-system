// --- Curve mock data (time-series for today, 5-min intervals from 06:00 to current hour) ---

function generateCurveData(basePower: number): InverterCurveData {
  const power = [];
  const voltage = [];
  const current = [];

  const now = new Date();
  const currentHour = now.getHours();
  const endMinute = currentHour <= 6 ? 0 : (currentHour >= 18 ? 720 : (currentHour - 6) * 60 + now.getMinutes());

  for (let m = 0; m <= endMinute; m += 5) {
    const h = 6 + Math.floor(m / 60);
    const min = m % 60;
    const time = `${String(h).padStart(2, "0")}:${String(min).padStart(2, "0")}`;

    // Solar bell curve: peak at noon (m=360), width ~300 min
    const normalizedM = (m - 360) / 180;
    const solarFactor = Math.max(0, Math.exp(-0.5 * normalizedM * normalizedM));
    const noise = 1 + (Math.random() - 0.5) * 0.08;

    const activePow = +(basePower * solarFactor * noise).toFixed(1);
    const dcPow = +(activePow * (1.01 + Math.random() * 0.02)).toFixed(1);
    const reactivePow = +(0.5 + Math.random() * 1.5).toFixed(1);

    power.push({ time, activePower: activePow, dcPower: dcPow, reactivePower: reactivePow });

    // Voltage: slight fluctuation around 803-806
    const baseV = 804;
    const vNoise = () => +(baseV + (Math.random() - 0.5) * 6).toFixed(1);
    voltage.push({ time, abVoltage: vNoise(), bcVoltage: vNoise(), caVoltage: vNoise() });

    // Current proportional to power
    const baseCurrent = activePow / 804 * 1000 / 1.732; // rough 3-phase calc
    const cNoise = () => +(baseCurrent + (Math.random() - 0.5) * 1.5).toFixed(1);
    current.push({ time, phaseA: Math.max(0, cNoise()), phaseB: Math.max(0, cNoise()), phaseC: Math.max(0, cNoise()) });
  }

  return { power, voltage, current };
}

const curveCache = new Map<string, InverterCurveData>();

export function getCurveDataForInverter(inverterId: string): InverterCurveData {
  if (curveCache.has(inverterId)) return curveCache.get(inverterId)!;

  const inv = solarInverters.find((i) => i.id === inverterId);
  const basePower = inv?.totalActivePower ?? 0;

  const data = generateCurveData(basePower);
  curveCache.set(inverterId, data);
  return data;
}
